"""Phase D of PLAN_DINOWM: does the latent SETTLE under a held action? THE GO/NO-GO.

The whole method reads one thing -- the ending latent after a settle tail, assigned to an
attractor. That presumes holding the action drives the latent somewhere and it STAYS. An
autoregressive ViT has no obligation to do that; it may drift, blur, or wander. If it does not
settle there are no attractors to discover and no centroids to cluster against, so Phases E and F
are not harder, they are unavailable. Untested on the block AND on Jenga.

TWO QUESTIONS, and the second is the one that decides whether Phase C's tracking error matters.

  1. CONVERGENCE.   Does ||z_{t+1} - z_t|| fall toward zero during the tail?
  2. CONTRACTIVITY. Does the tail pull slightly-WRONG trajectories into the RIGHT basin?
                    Tracking theta is a harder task than landing in the right basin -- the monitor
                    never reads theta. If errors that do not cross a boundary get absorbed, then
                    RMSE 0.320 is survivable. If the model instead hedges to a state between
                    basins and sits there, good tracking would not have saved it either.
     Measured as basin agreement BEFORE the tail vs AFTER it. Improvement = contractive.

Ground truth comes from the simulator run the same way: true action for H frames, zero force
after. The actions are regenerated by replaying phase_c_data.py's RNG in the same order.

Both checkpoints are tested. The single-step one is dino_wm's actual recipe and is what predicts
Jenga; the GTF-warm one says whether retraining would fix whatever goes wrong.
"""
import argparse, sys, time
from pathlib import Path
import numpy as np
import torch

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "src" / "systems"), str(ROOT / "eval"), "/home/sanger/wksp/dino_wm"]
import tipping_block as tb                                         # noqa: E402
import block_render as br                                          # noqa: E402
from phase_c_train import Predictor, NUM_HIST                      # noqa: E402
from run_phase3_monitor import T_ON, T_OFF                         # noqa: E402

OUT = ROOT / "results" / "phase_c"
STEPS, STRIDE = 450, 10


def true_actions(n_traj, seed=0):
    """Replay phase_c_data.py's RNG exactly: random_push then sample_lighting, per episode."""
    rng = np.random.default_rng(seed)
    thr = tb.topple_threshold(STEPS, T_ON, T_OFF)
    acts = []
    for _ in range(n_traj):
        a = tb.random_push(rng, STEPS, thr)
        tb.simulate(a, dt=tb.DT_DEFAULT)
        br.sample_lighting(rng)
        acts.append(a)
    return np.stack(acts)


def basin(t):
    """ORACLE basins, for scoring the model only. Phase E must discover these unsupervised."""
    return np.where(t < -1.4, 0, np.where(t > 1.4, 2, 1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--H", type=int, default=20, help="frames of true action before the tail")
    ap.add_argument("--L", type=int, default=40, help="settle-tail length (long, to see asymptote)")
    ap.add_argument("--n-test", type=int, default=60)
    args = ap.parse_args()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    t0 = time.time()

    Z = np.load(OUT / "latents.npy", mmap_mode="r")
    meta = np.load(OUT / "meta.npz"); S, A = meta["states"], meta["actions"]
    N, T = Z.shape[:2]; n_tr = N - args.n_test
    p = np.load(OUT / "phase_c_eval.npz")
    mu, sd, amu, asd = (float(p[k]) for k in ("mu", "sd", "amu", "asd"))

    print("ground truth: simulating true action for H then ZERO force ...", flush=True)
    acts = true_actions(N)
    th_before, th_after = [], []
    for i in range(n_tr, N):
        a = np.concatenate([acts[i][:args.H * STRIDE],
                            np.zeros(args.L * STRIDE, np.float64)])
        st, _ = tb.simulate(a, dt=tb.DT_DEFAULT)
        th_before.append(st[args.H * STRIDE, 0]); th_after.append(st[-1, 0])
    th_before = np.array(th_before); th_after = np.array(th_after)
    bt_b, bt_a = basin(th_before), basin(th_after)
    print(f"  true basin BEFORE tail {[int((bt_b==j).sum()) for j in range(3)]}   "
          f"AFTER tail {[int((bt_a==j).sum()) for j in range(3)]}")
    print(f"  the tail changes the true outcome on "
          f"{int((bt_b!=bt_a).sum())}/{args.n_test} episodes "
          f"(blocks still mid-fall at H)\n", flush=True)

    # theta readout, fit on TRUE train latents
    print("fitting theta readout ...", flush=True)
    ntr_r = 120
    Xr = np.asarray(Z[:ntr_r], np.float32).reshape(ntr_r * T, -1)
    yr = S[:ntr_r, :, 0].reshape(-1)
    xm = Xr.mean(0); Xc = Xr - xm
    Vk = np.linalg.svd(Xc[::3], full_matrices=False)[2][:256]
    P = Xc @ Vk.T
    Wg = np.linalg.solve(P.T @ P + 1e-2 * np.eye(256), P.T @ (yr - yr.mean()))
    ymean = yr.mean()
    readout = lambda X: ((X - xm) @ Vk.T) @ Wg + ymean              # noqa: E731
    del Xr, Xc, P

    zero_a = (0.0 - amu) / asd
    for tag, ckpt in (("single-step (dino_wm recipe)", "predictor.pt"),
                      ("GTF warm-started", "predictor_gtf_warm.pt")):
        if not (OUT / ckpt).exists():
            print(f"\n[{tag}] checkpoint missing, skipped"); continue
        model = Predictor().to(dev); model.load_state_dict(torch.load(OUT / ckpt)); model.eval()
        print(f"\n{'='*66}\n{tag}\n{'='*66}", flush=True)

        steps_norm, th_b_p, th_a_p, tails = [], [], [], []
        with torch.no_grad():
            for i in range(n_tr, N):
                z = ((torch.from_numpy(np.asarray(Z[i, :NUM_HIST], np.float32)).to(dev)
                      - mu) / sd)[None]
                aa = (torch.from_numpy(A[i]).to(dev) - amu) / asd
                # --- driven phase: true actions
                for t in range(NUM_HIST, args.H):
                    z = torch.cat([z, model(z[:, -NUM_HIST:], aa[None, t-NUM_HIST:t])[:, -1:]], 1)
                z_at_H = z[:, -1].clone()
                # --- settle tail: ZERO action
                az = torch.full((1, NUM_HIST, 1), zero_a, device=dev, dtype=z.dtype)
                d = []
                for _ in range(args.L):
                    nxt = model(z[:, -NUM_HIST:], az)[:, -1:]
                    d.append(float((nxt[:, 0] - z[:, -1]).norm()))
                    z = torch.cat([z, nxt], 1)
                tails.append(d)
                zb = (z_at_H[0].float().cpu().numpy() * sd + mu).reshape(1, -1)
                za = (z[0, -1].float().cpu().numpy() * sd + mu).reshape(1, -1)
                th_b_p.append(readout(zb)[0]); th_a_p.append(readout(za)[0])
                steps_norm.append(d[-1])

        tails = np.array(tails)
        E_end = np.stack([np.asarray(Z[i, -1], np.float32).ravel() for i in range(n_tr, N)])
        scale = float(np.linalg.norm(E_end - E_end.mean(0), axis=1).mean())
        th_b_p = np.array(th_b_p); th_a_p = np.array(th_a_p)

        print("1. CONVERGENCE  ||z_t+1 - z_t|| during the tail, as % of ending scale")
        js = [0, 1, 2, 4, 7, 11, 19, 29, args.L - 1]
        print("   step: " + "".join(f"{j:>8}" for j in js))
        print("   med : " + "".join(f"{100*np.median(tails[:, j])/scale:>8.2f}" for j in js))
        frac = float((tails[:, -1] / scale < 0.01).mean())
        print(f"   settled (<1% of scale at the end): {frac:.0%}   "
              f"{'PASS' if frac >= 0.90 else 'FAIL'}  (bar 90%)")
        r = tails[:, -1] / np.maximum(tails[:, 0], 1e-9)
        print(f"   contraction ratio last/first step: median {np.median(r):.3f}")

        print("\n2. CONTRACTIVITY  basin agreement before vs after the tail")
        ab = float((basin(th_b_p) == bt_b).mean()); aa_ = float((basin(th_a_p) == bt_a).mean())
        print(f"   before tail (at H={args.H}): {ab:.1%}")
        print(f"   after  tail (+{args.L}):     {aa_:.1%}   "
              f"{'CONTRACTIVE (+%.1f pts)' % (100*(aa_-ab)) if aa_ > ab else 'NOT contractive'}")
        print(f"   pred basin after {[int((basin(th_a_p)==j).sum()) for j in range(3)]}  "
              f"true {[int((bt_a==j).sum()) for j in range(3)]}")
        np.savez(OUT / f"phase_d_{ckpt.replace('.pt','')}.npz", tails=tails, scale=scale,
                 th_b=th_b_p, th_a=th_a_p, agree_before=ab, agree_after=aa_)
    print(f"\n({time.time()-t0:.0f}s)")


if __name__ == "__main__":
    main()
